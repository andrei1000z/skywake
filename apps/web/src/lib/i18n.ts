export type Lang = 'en' | 'ro';
const dicts: Record<Lang, Record<MsgKey, string>> = { en, ro };

function detect(): Lang {
  const saved = load<Lang | null>('lang', null);
  if (saved && saved in dicts) return saved;
  return typeof navigator !== 'undefined' && navigator.language?.toLowerCase().startsWith('ro') ? 'ro' : 'en';
}

let current: Lang = detect();
const listeners = new Set<() => void>();

export function setLang(l: Lang) {
  current = l;
  save('lang', l);
  document.documentElement.lang = l;
  listeners.forEach((f) => f());
}

export function t(key: MsgKey): string {
  return dicts[current][key];
}

export function useLang(): Lang {
  return useSyncExternalStore(
    (f) => {
      listeners.add(f);
      return () => listeners.delete(f);
    },
    () => current,
  );
}
